export function normalizeHexInput(raw: string): string | null {
	const hex = raw.trim().replace(/^#/, "");
	if (/^[0-9a-f]{3}$/i.test(hex)) return "#" + [...hex.toUpperCase()].map(c => c + c).join("");
	return /^[0-9a-f]{6}$/i.test(hex) ? "#" + hex.toUpperCase() : null;
}

export function hexToHsl(hex: string): { h: number; s: number; l: number } {
	const [h, s, l] = rgbToHsl(...parseHex(normalizeHexInput(hex) ?? "#000000"), false);
	return { h, s, l };
}

export function hslToHex(h: number, s: number, l: number): string {
	h = ((h % 360) + 360) % 360;
	s = Math.min(100, Math.max(0, s)) / 100;
	l = Math.min(100, Math.max(0, l)) / 100;
	const a = s * Math.min(l, 1 - l);
	return "#" + [0, 8, 4].map(n => {
		const k = (n + h / 30) % 12;
		const channel = l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1));
		return Math.round(channel * 255).toString(16).padStart(2, "0").toUpperCase();
	}).join("");
}

export function parseHex(hex: string): [number, number, number] {
	const clean = hex.trim().replace(/^#/, "");
	if (clean.length !== 6) return [0, 0, 0];
	const v = Number.parseInt(clean, 16);
	if (!Number.isFinite(v)) return [0, 0, 0];
	return [(v >> 16) & 255, (v >> 8) & 255, v & 255];
}

/**
 * Deterministic sRGB -> CMYK (%) matching `trasea-core/src/color.rs::rgb_to_cmyk`.
 */
export function rgbToCmykPct(r: number, g: number, b: number): [number, number, number, number] {
	const maxC = Math.max(r, g, b);
	const minC = Math.min(r, g, b);
	if (maxC <= 12 && maxC - minC <= 6) return [0, 0, 0, 100];
	if (minC === 255) return [0, 0, 0, 0];
	const rf = r / 255;
	const gf = g / 255;
	const bf = b / 255;
	const k = Math.max(0, Math.min(1, 1 - Math.max(rf, gf, bf)));
	if (k >= 0.9999) return [0, 0, 0, 100];
	const inv = 1 - k;
	const c = Math.max(0, Math.min(1, (1 - rf - k) / inv));
	const m = Math.max(0, Math.min(1, (1 - gf - k) / inv));
	const y = Math.max(0, Math.min(1, (1 - bf - k) / inv));
	return [Math.round(c * 100), Math.round(m * 100), Math.round(y * 100), Math.round(k * 100)];
}

export function rgbToHsl(r: number, g: number, b: number, round = true): [number, number, number] {
	const rf = r / 255;
	const gf = g / 255;
	const bf = b / 255;
	const max = Math.max(rf, gf, bf);
	const min = Math.min(rf, gf, bf);
	const l = (max + min) / 2;
	const d = max - min;
	if (d === 0) return [0, 0, round ? Math.round(l * 100) : l * 100];
	const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
	let h = 0;
	if (max === rf) h = ((gf - bf) / d + (gf < bf ? 6 : 0)) / 6;
	else if (max === gf) h = ((bf - rf) / d + 2) / 6;
	else h = ((rf - gf) / d + 4) / 6;
	return round ? [Math.round(h * 360), Math.round(s * 100), Math.round(l * 100)] : [h * 360, s * 100, l * 100];
}

export interface ColorCodes {
	hex: string;
	rgb: string;
	cmyk: string;
	hsl: string;
}

export function formatColorCodes(hexColor: string): ColorCodes {
	const upper = hexColor.trim().toUpperCase();
	const [r, g, b] = parseHex(upper);
	const [c, m, y, k] = rgbToCmykPct(r, g, b);
	const [h, s, l] = rgbToHsl(r, g, b);
	return {
		hex: upper,
		rgb: `rgb(${r}, ${g}, ${b})`,
		cmyk: `cmyk(${c}%, ${m}%, ${y}%, ${k}%)`,
		hsl: `hsl(${h}, ${s}%, ${l}%)`,
	};
}

export function buildGplPalette(name: string, colors: string[], spots: SpotColorMapping[]): string {
	const safeName = name.trim() || "Trasea Palette";
	const spotMap = new Map(spots.map(s => [s.hex.toUpperCase(), s.spotName.trim()]));
	const lines: string[] = [
		"GIMP Palette",
		`Name: ${safeName}`,
		"Columns: 4",
		`# Generated by Trasea ${APP_VERSION}`,
	];
	colors.forEach((hex, idx) => {
		const upper = hex.toUpperCase();
		const [r, g, b] = parseHex(upper);
		const spot = spotMap.get(upper);
		const label = spot ? `${spot} (${upper})` : `Trasea ${String(idx + 1).padStart(2, "0")} ${upper}`;
		lines.push(`${String(r).padStart(3, " ")} ${String(g).padStart(3, " ")} ${String(b).padStart(3, " ")}\t${label}`);
	});
	return `${lines.join("\n")}\n`;
}

export function buildJsonPalette(name: string, colors: string[], spots: SpotColorMapping[]): string {
	const spotMap = new Map(spots.map(s => [s.hex.toUpperCase(), s.spotName.trim()]));
	const payload = {
		name: name.trim() || "Trasea Palette",
		generator: `Trasea ${APP_VERSION}`,
		colors: colors.map((hex, idx) => {
			const upper = hex.toUpperCase();
			const [r, g, b] = parseHex(upper);
			const [c, m, y, k] = rgbToCmykPct(r, g, b);
			const [h, s, l] = rgbToHsl(r, g, b);
			const spotName = spotMap.get(upper) || null;
			return {
				index: idx + 1,
				hex: upper,
				rgb: [r, g, b],
				cmyk: [c, m, y, k],
				hsl: [h, s, l],
				spotName,
			};
		}),
	};
	return `${JSON.stringify(payload, null, 2)}\n`;
}

export function buildCssPalette(name: string, colors: string[], spots: SpotColorMapping[]): string {
	const spotMap = new Map(spots.map(s => [s.hex.toUpperCase(), s.spotName.trim()]));
	const lines: string[] = [`/* ${name.trim() || "Trasea Palette"} — Generated by Trasea ${APP_VERSION} */`, ":root {"];
	colors.forEach((hex, idx) => {
		const upper = hex.toUpperCase();
		const spot = spotMap.get(upper);
		const slug = spot
			? spot.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")
			: `color-${String(idx + 1).padStart(2, "0")}`;
		lines.push(`\t--trasea-${slug || `color-${idx + 1}`}: ${upper};`);
	});
	lines.push("}");
	return `${lines.join("\n")}\n`;
}

export function normalizeShortcutKey(key: string): string {
	if (key === " ") return "Space";
	if (key.length === 1) return key.toUpperCase();
	if (key === "Escape") return "Esc";
	return key;
}

export function eventToShortcutString(e: KeyboardEvent): string | null {
	if (["Control", "Shift", "Alt", "Meta"].includes(e.key)) return null;
	const parts: string[] = [];
	if (e.ctrlKey || e.metaKey) parts.push("Ctrl");
	if (e.shiftKey) parts.push("Shift");
	if (e.altKey) parts.push("Alt");
	if (parts.length === 0) return null;
	parts.push(normalizeShortcutKey(e.key));
	return parts.join("+");
}

export function effectiveShortcuts(custom: Record<string, string>): Record<ShortcutAction, string> {
	const merged: Record<ShortcutAction, string> = { ...DEFAULT_SHORTCUTS };
	for (const action of Object.keys(DEFAULT_SHORTCUTS) as ShortcutAction[]) {
		const v = custom[action]?.trim();
		if (v) merged[action] = v;
	}
	return merged;
}

export function matchShortcut(e: KeyboardEvent, combo: string): boolean {
	const cur = eventToShortcutString(e);
	if (!cur) return false;
	return cur.toLowerCase() === combo.trim().toLowerCase();
}
